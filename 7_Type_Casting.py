"""
Type Casting:-

The process of converting the data type of a value or a variable is known as type casting

Types of Type Casting:

1) Implicit Type Casting:-

Implicit type casting is performed automaticaaly by the python interpreter

2) Explicit Type Casting:-

Explicit type casting is performed by the programmer

"""

# Implicit Type Casting

a=10
b=12.5
print(a+b)

# As we see that a variable contains value with interger data type and b variable contains value with float data type. So python interpreter convert the integer variable to float for performing addition 

# Explicit Type Casting

x="2"
y=19
print(int(x)+y) # Converting x into integer
print(x+str(y)) # Converting y to string


